/**
 * Drug Mechanism Match — the drugs.
 *
 * One entry per CLASS (a group of drugs that share a mechanism). A board
 * shows one drug from each of several classes, chosen at random from
 * `drugs`, beside each class's mechanism — so a board never has two drugs
 * with the same mechanism, and every pairing has exactly one right answer.
 *
 *   mech  — the mechanism, as it appears on the right-hand card
 *   uses  — clinical uses (shown as a hint in Guided mode)
 *   adverse — adverse effects and cautions (the study deck)
 *   fact  — the ONE thing to remember about what it costs the patient (or
 *           its defining use): the follow-up question after each board.
 *           Facts are written to be distinct across classes, so a wrong
 *           option is never also true of the drug asked about.
 *
 * Organised by system and deck. Content follows First Aid for USMLE Step 1.
 * Anticoagulants and antiplatelets belong to Haematology in First Aid and
 * will arrive with that system.
 */

